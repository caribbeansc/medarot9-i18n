#!/usr/bin/env python3
"""cgfx_tex.py - Textures embedded in 3DS CGFX models (.bcmdl/.bcres): list, extract and replace.

The signs on the buildings of the field (学院正門, グラウンド/部室棟/体育館/武道場, 探検部...) are NOT text: they are
textures inside the map model (story/mdl/mNNN.bcmdl, e.g. 'm101_name', 'm160_sign'); so are the 3D labels of
battle (battle/mdl/TGT_N_*.bcmdl) and the floating exit label (story/mdl/e_f_out.bcmdl). Format of each
texture (TXOB):

    u32 type (0x20000011) | "TXOB" | revision | name (rel) | n_userdata | userdata (rel) | height | width |
    GL format | GL type | mipmap levels | texobj | location | PICA format | image (rel) ->
    image: height | width | size | data (rel) | ...

The data are PICA200 8x8 Morton tiles (same formats as CTPK), level 0 followed by the mipmaps. The replacement
re-encodes in the SAME format and size, so the file keeps its length and no offset changes. With the original as
reference (orig), the ETC1 blocks and the mipmap areas that do not change are copied byte for byte; the mipmaps of
the edited area are regenerated by downscaling the new image.

  python tools/tex/cgfx_tex.py list <bcmdl>
  python tools/tex/cgfx_tex.py dump <bcmdl> <dir> [name]
  python tools/tex/cgfx_tex.py replace <bcmdl> <name> <png> <out.bcmdl>
(texlib.py integrates this: a spec with "rel": "story/mdl/m101.bcmdl", "tex": "m101_name")
"""
import struct
import sys
from pathlib import Path

from PIL import Image, ImageChops

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from ctpk_tool import BPP, FMT_NAMES, decode_tex, encode_image  # noqa: E402,F401


def _rel(d: bytes, pos: int) -> int:
    return pos + struct.unpack_from('<I', d, pos)[0]


def _cstr(d: bytes, pos: int) -> str:
    return d[pos:d.index(b'\x00', pos)].decode('ascii', 'replace')


def level_size(w: int, h: int, fmt: int) -> int:
    return w * h * BPP[fmt] // 8


def textures(d: bytes):
    """[{name, w, h, fmt, mips, off, size}] of each TXOB with an image."""
    out = []
    i = -1
    while True:
        i = d.find(b'TXOB', i + 1)
        if i < 0:
            break
        if i < 4 or struct.unpack_from('<I', d, i - 4)[0] != 0x20000011:
            continue
        try:
            name = _cstr(d, _rel(d, i + 8))
            h, w = struct.unpack_from('<II', d, i + 20)
            mips = struct.unpack_from('<I', d, i + 36)[0]
            fmt = struct.unpack_from('<I', d, i + 48)[0]
            img = _rel(d, i + 52)
            ih, iw, size = struct.unpack_from('<III', d, img)
            off = _rel(d, img + 12)
        except (struct.error, ValueError):
            continue
        if fmt not in BPP or (ih, iw) != (h, w) or off + size > len(d):
            continue
        out.append({'name': name, 'w': w, 'h': h, 'fmt': fmt, 'mips': mips, 'off': off, 'size': size})
    return out


def get(d: bytes, name: str):
    for t in textures(d):
        if t['name'] == name:
            return t
    raise KeyError(f'no texture "{name}" (available: {", ".join(t["name"] for t in textures(d))})')


def levels(t: dict):
    """[(w, h, relative offset, size)] of the levels present in the data (level 0 + mipmaps >= 8x8)."""
    out = []
    w, h, o = t['w'], t['h'], 0
    for _ in range(max(1, t['mips'])):
        if w < 8 or h < 8:
            break
        sz = level_size(w, h, t['fmt'])
        if o + sz > t['size']:
            break
        out.append((w, h, o, sz))
        o += sz
        w, h = w // 2, h // 2
    return out


def decode(d: bytes, t: dict) -> Image.Image:
    return decode_tex(t['fmt'], t['w'], t['h'], d[t['off']:t['off'] + level_size(t['w'], t['h'], t['fmt'])])


def _changed_mask(a: Image.Image, b: Image.Image, grow=1):
    """L mask (255 = different) between two RGBA images of the same size, dilated by grow px."""
    diff = ImageChops.difference(a, b)
    m = None
    for ch in diff.split():
        c = ch.point(lambda v: 255 if v else 0)
        m = c if m is None else ImageChops.lighter(m, c)
    for _ in range(grow):
        m = ImageChops.lighter(m, ImageChops.offset(m, 1, 0))
        m = ImageChops.lighter(m, ImageChops.offset(m, -1, 0))
        m = ImageChops.lighter(m, ImageChops.offset(m, 0, 1))
        m = ImageChops.lighter(m, ImageChops.offset(m, 0, -1))
    return m


def encode_levels(img: Image.Image, t: dict, orig: bytes = None) -> bytes:
    """Level 0 + mipmaps in the texture's format; same length as the original. orig = bytes of the ORIGINAL file
    that holds this same texture at the same offset: whatever does not change is kept byte for byte."""
    img = img.convert('RGBA')
    if img.size != (t['w'], t['h']):
        raise ValueError(f"size {img.size} != {(t['w'], t['h'])}")
    fmt = t['fmt']
    od = None
    if orig is not None:
        to = get(orig, t['name'])
        if (to['off'], to['size'], to['fmt'], to['w'], to['h']) != (t['off'], t['size'], fmt, t['w'], t['h']):
            raise ValueError(f'{t["name"]}: the original does not have the texture at the same offset/format')
        od = orig[to['off']:to['off'] + to['size']]
    buf = bytearray()
    o0 = None
    for i, (w, h, o, sz) in enumerate(levels(t)):
        ref = None
        if i == 0:
            im = img
            if od is not None:
                o0 = decode_tex(fmt, w, h, od[o:o + sz])
                ref = (o0, od[o:o + sz])
        else:
            new_l = img.resize((w, h), Image.BOX)
            if od is not None:
                ol = decode_tex(fmt, w, h, od[o:o + sz])
                mask = _changed_mask(new_l, o0.resize((w, h), Image.BOX))
                im = ol.copy()
                im.paste(new_l, (0, 0), mask)
                ref = (ol, od[o:o + sz])
            else:
                im = new_l
        buf += encode_image(im, fmt, ref)
    if len(buf) > t['size']:
        raise ValueError(f'encoded {len(buf)} > {t["size"]}')
    return bytes(buf)


def replace(d: bytes, name: str, img: Image.Image, orig: bytes = None) -> bytes:
    """d with the texture name re-encoded from img (same format, size and offsets)."""
    t = get(d, name)
    enc = encode_levels(img, t, orig)
    out = bytearray(d)
    out[t['off']:t['off'] + len(enc)] = enc
    return bytes(out)


def changed_outside(old: bytes, new: bytes, t: dict):
    """Byte ranges [start, end) that change OUTSIDE the data of texture t (must be [])."""
    if len(old) != len(new):
        return [(0, max(len(old), len(new)))]
    out = []
    a, b = t['off'], t['off'] + t['size']
    for lo, hi in ((0, a), (b, len(old))):
        i = lo
        while i < hi:
            if old[i] != new[i]:
                j = i
                while j < hi and old[j] != new[j]:
                    j += 1
                out.append((i, j))
                i = j
            else:
                i += 1
    return out


def main(argv):
    if len(argv) < 2:
        print(__doc__)
        return 1
    cmd, src = argv[0], Path(argv[1])
    d = src.read_bytes()
    if cmd == 'list':
        for t in textures(d):
            print(f"{t['name']:32} {t['w']:4}x{t['h']:<4} {FMT_NAMES.get(t['fmt'], t['fmt']):8} mips {t['mips']} "
                  f"@{t['off']:#x} {t['size']}B")
    elif cmd == 'dump':
        out = Path(argv[2])
        out.mkdir(parents=True, exist_ok=True)
        for t in textures(d):
            if len(argv) > 3 and t['name'] != argv[3]:
                continue
            decode(d, t).save(out / f"{src.stem}__{t['name']}.png")
        print('ok', out)
    elif cmd == 'replace':
        new = replace(d, argv[2], Image.open(argv[3]), orig=d)
        Path(argv[4]).write_bytes(new)
        bad = changed_outside(d, new, get(d, argv[2]))
        print('ok', argv[4], 'same size' if len(new) == len(d) else 'DIFFERENT SIZE',
              'only the texture changes' if not bad else f'CHANGES OUTSIDE THE TEXTURE: {bad[:5]}')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
